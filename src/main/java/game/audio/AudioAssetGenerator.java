package game.audio;

import javax.sound.sampled.AudioFormat;
import javax.sound.sampled.AudioInputStream;
import javax.sound.sampled.AudioSystem;
import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

/** Generates original, cinematic WAV music/effects on first run. */
public final class AudioAssetGenerator {
    private static final float SAMPLE_RATE = 22050f;
    private static final AudioFormat FORMAT = new AudioFormat(SAMPLE_RATE, 16, 1, true, false);
    private static final Path DEFAULT_DIRECTORY = Path.of(System.getProperty("user.home"), ".code-escape", "audio");
    private static final String AUDIO_VERSION = "epic-v2";
    private static volatile boolean generated;

    private AudioAssetGenerator() { }

    public static Path audioDirectory() { return DEFAULT_DIRECTORY; }

    /** Creates missing assets only, preserving WAV files supplied or customized by the team. */
    public static synchronized void ensureAssets() throws IOException {
        if (generated && Files.isDirectory(DEFAULT_DIRECTORY)) return;
        Files.createDirectories(DEFAULT_DIRECTORY);

        // A versioned upgrade replaces only files generated by the previous placeholder mixer.
        // Custom WAV files are kept unless they are one of the known placeholder names and a
        // regeneration is explicitly triggered by deleting the .audio-version marker.
        Path versionFile = DEFAULT_DIRECTORY.resolve(".audio-version");
        boolean legacyVersion = Files.exists(versionFile)
                && AUDIO_VERSION.equals(Files.readString(versionFile, StandardCharsets.UTF_8).trim());

        if (!legacyVersion) {
            writeIfMissing("bgm-start.wav", .48, 1);
            writeIfMissing("bgm-game.wav", .55, 2);
            writeIfMissing("bgm-quiz.wav", .48, 3);
            writeIfMissing("sfx-button.wav", .30, 10);
            writeIfMissing("sfx-correct.wav", .48, 11);
            writeIfMissing("sfx-wrong.wav", .42, 12);
            writeIfMissing("sfx-attack.wav", .55, 13);
            writeIfMissing("sfx-hit.wav", .55, 14);
            writeIfMissing("sfx-victory.wav", .65, 15);
            writeIfMissing("sfx-defeat.wav", .55, 16);
            writeIfMissing("sfx-chest.wav", .55, 17);
            Files.writeString(versionFile, AUDIO_VERSION, StandardCharsets.UTF_8);
        }
        generated = true;
    }

    /** Optional CLI: java game.audio.AudioAssetGenerator [output-directory]. */
    public static void main(String[] args) throws IOException {
        Path output = args.length == 0 ? DEFAULT_DIRECTORY : Path.of(args[0]);
        Files.createDirectories(output);
        generateAll(output);
        System.out.println("Generated cinematic WAV audio assets in " + output.toAbsolutePath());
    }

    private static void generateAll(Path output) throws IOException {
        write(output.resolve("bgm-start.wav"), .48, 1);
        write(output.resolve("bgm-game.wav"), .55, 2);
        write(output.resolve("bgm-quiz.wav"), .48, 3);
        write(output.resolve("sfx-button.wav"), .30, 10);
        write(output.resolve("sfx-correct.wav"), .48, 11);
        write(output.resolve("sfx-wrong.wav"), .42, 12);
        write(output.resolve("sfx-attack.wav"), .55, 13);
        write(output.resolve("sfx-hit.wav"), .55, 14);
        write(output.resolve("sfx-victory.wav"), .65, 15);
        write(output.resolve("sfx-defeat.wav"), .55, 16);
        write(output.resolve("sfx-chest.wav"), .55, 17);
    }

    private static void writeIfMissing(String filename, double amplitude, int preset) throws IOException {
        Path path = DEFAULT_DIRECTORY.resolve(filename);
        if (!Files.exists(path)) write(path, amplitude, preset);
    }

    private static void write(Path path, double amplitude, int preset) throws IOException {
        boolean music = preset >= 1 && preset <= 3;
        int lengthSeconds = music ? 12 : effectLength(preset);
        int frames = (int) (SAMPLE_RATE * lengthSeconds);
        byte[] pcm = new byte[frames * 2];

        double seed = 0.0;
        for (int i = 0; i < frames; i++) {
            double t = i / SAMPLE_RATE;
            double sample;
            if (music) {
                sample = generateMusic(preset, t, amplitude);
            } else {
                sample = generateEffect(preset, t, amplitude);
            }

            seed = (seed * 0.72 + (pseudoRandom(i) * 0.28));
            if (preset == 13 || preset == 14) {
                sample += seed * 0.08 * amplitude;
            }

            sample = Math.max(-1.0, Math.min(1.0, sample));
            short value = (short) (sample * Short.MAX_VALUE);
            pcm[i * 2] = (byte) (value & 0xff);
            pcm[i * 2 + 1] = (byte) ((value >>> 8) & 0xff);
        }

        try (AudioInputStream audio = new AudioInputStream(new ByteArrayInputStream(pcm), FORMAT, frames)) {
            AudioSystem.write(audio, javax.sound.sampled.AudioFileFormat.Type.WAVE, path.toFile());
        }
    }

    private static double generateMusic(int preset, double t, double amplitude) {
        double[] scale;
        double tempo;
        if (preset == 1) {
            scale = new double[]{65.41, 98.00, 130.81, 146.83, 196.00}; // C/E low, heroic intro
            tempo = 0.50;
        } else if (preset == 2) {
            scale = new double[]{55.00, 82.41, 110.00, 98.00, 73.42, 82.41}; // tense fifths
            tempo = 0.36;
        } else {
            scale = new double[]{73.42, 110.00, 146.83, 164.81, 220.00};
            tempo = 0.30;
        }

        int step = (int) Math.floor(t / tempo);
        int noteIndex = (step * 3 + preset) % scale.length;
        double noteTime = t % tempo;
        double edge = Math.max(0.0, Math.min(1.0, Math.min(noteTime / 0.025, (tempo - noteTime) / 0.18)));

        double root = scale[noteIndex];
        double bass = Math.sin(2 * Math.PI * root * 0.5 * t);
        double lead = Math.sin(2 * Math.PI * root * t);
        double octave = 0.34 * Math.sin(2 * Math.PI * root * 2 * t);
        double fifth = 0.22 * Math.sin(2 * Math.PI * root * 1.5 * t);

        // Slow orchestral pad gives the track width and a cinematic swell.
        double pad = 0.16 * (Math.sin(2 * Math.PI * root * 0.25 * t)
                + Math.sin(2 * Math.PI * root * 0.375 * t));

        // Deep kick accents every half-bar; the high tick creates a rhythmic pulse.
        double beat = t % 1.0;
        double kick = beat < 0.14 ? Math.sin(2 * Math.PI * (95 - beat * 420) * beat) * (1 - beat / 0.14) : 0;
        double tickTime = t % (tempo * 0.5);
        double tick = tickTime < 0.025 ? Math.sin(2 * Math.PI * 2400 * tickTime) * (1 - tickTime / 0.025) : 0;

        double swell = 0.82 + 0.18 * Math.sin(2 * Math.PI * t / 6.0);
        double melody = (lead * 0.42 + octave + fifth) * edge;
        return amplitude * swell * (melody + bass * 0.25 + pad + kick * 0.30 + tick * 0.10);
    }

    private static double generateEffect(int preset, double t, double amplitude) {
        switch (preset) {
            case 10: return fade(t, 0.12, amplitude) * (Math.sin(2 * Math.PI * 660 * t) * 0.7 + Math.sin(2 * Math.PI * 990 * t) * 0.3);
            case 11: return reward(t, 0.75, amplitude, new double[]{523.25, 659.25, 783.99, 1046.50});
            case 12: return error(t, 0.55, amplitude, 280);
            case 13: return impact(t, 0.28, amplitude, 150, 520);
            case 14: return impact(t, 0.36, amplitude, 95, 180);
            case 15: return reward(t, 1.55, amplitude, new double[]{261.63, 329.63, 392.00, 523.25, 659.25, 783.99, 1046.50});
            case 16: return descending(t, 1.45, amplitude, new double[]{392, 329.63, 261.63, 196, 146.83});
            case 17: return reward(t, 0.90, amplitude, new double[]{440, 659.25, 880, 1318.51});
            default: return 0;
        }
    }

    private static double reward(double t, double duration, double amplitude, double[] notes) {
        double slot = duration / notes.length;
        int index = (int) Math.floor(t / slot);
        if (index >= notes.length) return 0;
        double lt = t - index * slot;
        double envelope = fade(lt, slot, amplitude);
        double f = notes[index];
        return envelope * (Math.sin(2 * Math.PI * f * lt) * 0.70
                + Math.sin(2 * Math.PI * f * 2 * lt) * 0.22
                + Math.sin(2 * Math.PI * f * 1.5 * lt) * 0.12);
    }

    private static double descending(double t, double duration, double amplitude, double[] notes) {
        double slot = duration / notes.length;
        int index = (int) Math.floor(t / slot);
        if (index >= notes.length) return 0;
        double lt = t - index * slot;
        double f = notes[index];
        return fade(lt, slot, amplitude) * (Math.sin(2 * Math.PI * f * lt) * 0.75 + Math.sin(2 * Math.PI * f * 0.5 * lt) * 0.25);
    }

    private static double impact(double t, double duration, double amplitude, double low, double high) {
        if (t > duration) return 0;
        double decay = Math.exp(-8 * t / duration);
        double frequency = low + (high - low) * Math.exp(-12 * t);
        double noise = pseudoRandom((int) (t * 22050));
        return amplitude * decay * (Math.sin(2 * Math.PI * frequency * t) * 0.72 + noise * 0.28);
    }

    private static double error(double t, double duration, double amplitude, double frequency) {
        if (t > duration) return 0;
        double decay = Math.exp(-6 * t);
        double wobble = frequency * (1 - 0.35 * t / duration);
        return amplitude * decay * Math.sin(2 * Math.PI * wobble * t);
    }

    private static double fade(double t, double duration, double amplitude) {
        if (t < 0 || t > duration) return 0;
        double attack = Math.min(1.0, t / 0.018);
        double release = Math.min(1.0, (duration - t) / 0.10);
        return amplitude * attack * Math.max(0, release);
    }

    private static int effectLength(int preset) {
        if (preset == 15) return 2;
        if (preset == 16) return 2;
        if (preset == 11) return 1;
        return 1;
    }

    private static double pseudoRandom(int i) {
        int x = i * 1103515245 + 12345;
        x ^= x >> 16;
        return ((x & 0xffff) / 32767.5) - 1.0;
    }
}
